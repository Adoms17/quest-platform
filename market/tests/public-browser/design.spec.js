import { expect, test } from '@playwright/test'
import { publicRow } from '../publicDesignData.mjs'
const screenshots = process.env.MARKET_PUBLIC_BUILT_TEST ? 'qa/filter-availability/screens' : 'qa/public-design'
const rows = [publicRow(1), publicRow(2)]
test.beforeEach(async ({ context }) => {
  await context.route('**/*', async route => {
    const url = new URL(route.request().url())
    if (url.origin !== 'http://127.0.0.1:4194') return route.abort()
    if (url.pathname === '/rest/v1/rpc/read_shop_catalog') {
      const body = route.request().postDataJSON()
      return route.fulfill({ json: body.p_slug ? rows.filter(row => row.slug === body.p_slug && (!body.p_version_id || row.version_id === body.p_version_id)) : rows })
    }
    return route.continue()
  })
})
test('public UI viewport matrix: catalog, details, demo, no overflow and local font', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  for (const width of [320, 360, 390, 430, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: width < 768 ? 844 : 1024 })
    for (const [name, path] of [['catalog', '/'], ['details', `/quests/public-1?version=${rows[0].version_id}`], ['demo', `/quests/public-1/demo?version=${rows[0].version_id}`]]) {
      await page.goto(path)
      await expect(page.locator('#page-title')).toBeVisible()
      if (name === 'catalog') await expect(page.getByRole('article')).toHaveCount(2)
      else await expect(page.getByRole('heading', { name: name === 'details' ? 'Подойдёт вашей компании?' : 'Публичный пример' })).toBeVisible()
      await page.evaluate(() => document.fonts.ready)
      if (width === 1440 && name === 'catalog') {
        const session = await page.context().newCDPSession(page)
        await session.send('DOM.enable'); await session.send('CSS.enable')
        const { root } = await session.send('DOM.getDocument')
        const { nodeId } = await session.send('DOM.querySelector', { nodeId: root.nodeId, selector: 'h1' })
        const { fonts } = await session.send('CSS.getPlatformFontsForNode', { nodeId })
        expect(fonts.some(font => font.isCustomFont && font.familyName.includes('Manrope'))).toBe(true)
        await session.detach()
      }
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if (name === 'details') {
        const tile = page.locator('.public-compatibility-summary > div').first()
        const label = await tile.locator('dt').boundingBox()
        const value = await tile.locator('dd').boundingBox()
        expect(value.y).toBeGreaterThanOrEqual(label.y + label.height)
      }
      if (name === 'demo') {
        await expect(page.getByRole('heading', { name: 'Демо квеста', exact: true })).toBeVisible()
        await expect(page.getByRole('note')).toContainText('выбранной версии без проверки ответа')
        await expect(page.locator('.product-demo').getByRole('radio')).toHaveCount(0)
        await expect(page.locator('.standalone-example').getByRole('radio')).toHaveCount(3)
        await expect(page.locator('.product-demo').getByRole('button', { name: /Проверить/ })).toHaveCount(0)
      }
      await page.screenshot({ path: `${screenshots}/${name}-${width}.png`, fullPage: true })
    }
  }
  expect(errors).toEqual([])
})
test('quick filters preserve other groups, discard drafts, and return keyboard focus to each initiator', async ({ page }) => {
  for (const width of [320, 360, 390, 430, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/?q=Проверочный&print=none')
    await expect(page.getByRole('article')).toHaveCount(1)
    const dialog = page.getByRole('dialog')
    for (const [id, label] of [['age', '8–12 лет'], ['venue', 'Помещение Б']]) {
      const trigger = page.locator(`#catalog-filter-${id}`)
      await trigger.focus()
      await page.keyboard.press('Enter')
      await expect(dialog.getByRole('button', { name: 'Закрыть фильтры' })).toBeFocused()
      await page.keyboard.press('Tab')
      if (id === 'venue') {
        await expect(dialog.getByLabel('Помещение А', { exact: true })).toBeFocused()
        await page.keyboard.press('Tab')
      }
      await expect(dialog.getByLabel(label, { exact: true })).toBeFocused()
      await page.keyboard.press('Space')
      await page.keyboard.press('Escape')
      await expect(trigger).toBeFocused()
      await page.keyboard.press('Enter')
      await expect(dialog.getByLabel(label, { exact: true })).not.toBeChecked()
      await dialog.getByLabel(label, { exact: true }).check()
      await page.screenshot({ path: `${screenshots}/quick-${id}-${width}.png`, fullPage: true })
      await dialog.getByRole('button', { name: 'Показать 1 квест', exact: true }).click()
      await expect(trigger).toBeFocused()
      expect(new URL(page.url()).searchParams.get('print')).toBe('none')
      expect(new URL(page.url()).searchParams.get('q')).toBe('Проверочный')
      expect(new URL(page.url()).searchParams.has(id)).toBe(true)
      await page.goBack()
      expect(new URL(page.url()).searchParams.has(id)).toBe(false)
      await page.goForward()
      expect(new URL(page.url()).searchParams.has(id)).toBe(true)
      await trigger.click()
      await dialog.getByRole('button', { name: 'Сбросить фильтры' }).click()
      await dialog.getByRole('button', { name: 'Показать 1 квест', exact: true }).click()
      await expect(trigger).toBeFocused()
      expect(new URL(page.url()).searchParams.has(id)).toBe(false)
      expect(new URL(page.url()).searchParams.get('print')).toBe('none')
    }
  }
})

test('loading, error/retry, empty, missing and withdrawn stay distinct without fixture fallback', async ({ page }) => {
  let scenario = 'error'
  await page.route('**/rest/v1/rpc/read_shop_catalog', route => {
    if (scenario === 'error') return route.fulfill({ status: 503, body: '{}' })
    if (scenario === 'withdrawn') return route.fulfill({ json: [{ ...rows[0], state: 'withdrawn', payload: null, offer: null }] })
    return route.fulfill({ json: [] })
  })
  await page.goto('/')
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.locator('.empty-illustration, .standalone-example')).toHaveCount(0)
  await expect(page.getByRole('article')).toHaveCount(0)
  await page.screenshot({ path: `${screenshots}/error.png`, fullPage: true })
  scenario = 'empty'
  await page.getByRole('button', { name: 'Повторить загрузку' }).click()
  await expect(page.getByRole('heading', { name: 'Каталог пока пуст' })).toBeVisible()
  await expect(page.locator('.empty-illustration')).toHaveCount(0)
  await page.goto('/quests/missing')
  await expect(page.getByRole('heading', { name: 'Квест не найден' })).toBeVisible()
  scenario = 'withdrawn'
  await page.goto(`/quests/public-1/demo?version=${rows[0].version_id}`)
  await expect(page.getByRole('heading', { name: 'Версия снята с публикации' })).toBeVisible()
  await expect(page.locator('.standalone-example')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Публичный пример' })).toHaveCount(0)
})


test('keyboard Details CTA restores its own focus and scroll on explicit return and browser Back', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?q=Проверочный')
  await expect(page.getByRole('article')).toHaveCount(2)
  const cta = page.getByRole('link', { name: 'Подробнее: Проверочный квест 2', exact: true })
  const expectedId = `quest-details-${rows[1].version_id}`
  await expect(cta).toHaveAttribute('id', expectedId)
  expect(await page.locator(`[id="${expectedId}"]`).count()).toBe(1)
  for (const returnMode of ['explicit', 'back']) {
    // Reach the CTA through keyboard navigation, not the separate title link.
    for (let step = 0; step < 24 && !(await cta.evaluate(el => el === document.activeElement)); step++) await page.keyboard.press('Tab')
    await expect(cta).toBeFocused()
    await page.evaluate(() => document.fonts.ready)
    const y = await page.evaluate(() => scrollY)
    expect(y).toBeGreaterThan(300)
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Подойдёт вашей компании?' })).toBeVisible()
    await expect(page).toHaveURL(new RegExp(`/quests/public-2\\?version=${rows[1].version_id}$`))
    if (returnMode === 'back') await page.goBack()
    else {
      const back = page.getByRole('link', { name: 'Все квесты' })
      await back.focus()
      await page.keyboard.press('Enter')
    }
    await expect(cta).toBeFocused()
    await expect(page.locator('#quest-public-2')).not.toBeFocused()
    await expect.poll(() => page.evaluate(() => scrollY)).toBeCloseTo(y, -1)
    await expect(page).toHaveURL(/q=/)
  }
})

test('standalone example is independent, keyboard usable and performs no requests or persistent writes', async ({ page }) => {
  await page.addInitScript(() => {
    window.exampleWrites = []
    const save = Storage.prototype.setItem
    Storage.prototype.setItem = function (...args) { window.exampleWrites.push('storage'); return save.apply(this, args) }
    const open = IDBFactory.prototype.open
    IDBFactory.prototype.open = function (...args) { window.exampleWrites.push('indexedDB'); return open.apply(this, args) }
  })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/quests/public-1/demo?version=${rows[0].version_id}`)
  const example = page.locator('.standalone-example')
  await expect(example).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  const requests = []
  page.on('request', request => requests.push(request.method() + ' ' + new URL(request.url()).pathname))
  await page.evaluate(() => { window.exampleWrites = [] })
  await example.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(example.getByRole('status')).toContainText('Сначала выберите')
  const first = example.getByRole('radio', { name: 'Компас' })
  await first.focus()
  await page.keyboard.press('ArrowRight')
  await expect(example.getByRole('radio', { name: 'Фонарь' })).toBeChecked()
  await example.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(example.getByRole('status')).toContainText('не определяет стороны света')
  await page.screenshot({ path: `${screenshots}/demo-feedback-retry-390.png`, fullPage: true })
  await first.check()
  await example.getByRole('button', { name: 'Проверить', exact: true }).click()
  await expect(example.getByRole('status')).toContainText('Верно!')
  await expect(page.locator('.product-demo')).toContainText(rows[0].payload.demo.publicDemo.value.question)
  await page.screenshot({ path: `${screenshots}/demo-feedback-correct-390.png`, fullPage: true })
  await example.getByRole('button', { name: 'Начать заново' }).click()
  await expect(first).toBeFocused()
  await expect(first).not.toBeChecked()
  expect(requests).toEqual([])
  expect(await page.evaluate(() => window.exampleWrites)).toEqual([])
  await page.reload()
  await expect(example.getByRole('status')).toContainText('Выберите вариант')
  await expect(first).not.toBeChecked()
})

test('price sorting preserves filters, history, pinned return and rejects mixed currencies', async ({ page }) => {
  const priced = [rows[0], { ...rows[1], offer: { ...rows[1].offer, amount_minor: 9900 } }]
  await page.route('**/rest/v1/rpc/read_shop_catalog', route => {
    const body = route.request().postDataJSON()
    return route.fulfill({ json: body.p_slug ? priced.filter(row => row.slug === body.p_slug) : priced })
  })
  await page.goto('/?q=Проверочный')
  const sort = page.getByLabel('Порядок квестов')
  await sort.selectOption('price-asc')
  await expect(page.getByRole('article').first()).toContainText('Проверочный квест 2')
  await expect(page).toHaveURL(/sort=price-asc/)
  await expect(page.getByRole('searchbox')).toHaveValue('Проверочный')
  await page.getByRole('link', { name: 'Подробнее: Проверочный квест 2', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(rows[1].version_id))
  await page.getByRole('link', { name: 'Все квесты' }).click()
  await expect(sort).toHaveValue('price-asc')
  await expect(page.getByRole('link', { name: 'Подробнее: Проверочный квест 2', exact: true })).toBeFocused()
  await sort.selectOption('price-desc')
  await expect(page.getByRole('article').first()).toContainText('Проверочный квест 1')
  await page.goBack()
  await expect(sort).toHaveValue('price-asc')
  await page.goForward()
  await expect(sort).toHaveValue('price-desc')
  await page.reload()
  await expect(sort).toHaveValue('price-desc')
  await page.screenshot({ path: `${screenshots}/sort-price-desc.png`, fullPage: true })
  priced[1].offer.currency = 'USD'
  await page.reload()
  await expect(sort).toHaveValue('default')
  await expect(sort.locator('option[value="price-asc"]')).toHaveJSProperty('disabled', true)
  await expect(page.getByText(/Сортировка по цене доступна только/)).toBeVisible()
  await expect(page.getByRole('article').first()).toContainText('Проверочный квест 1')
})

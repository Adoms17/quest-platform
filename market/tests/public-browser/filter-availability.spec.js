import { expect, test } from '@playwright/test'
import { minimalPublicRow, publicRow } from '../publicDesignData.mjs'
import { validPublicItem } from '../../src/publicCatalogContract.js'

const unknown = () => minimalPublicRow()
test.beforeEach(async ({ context }) => {
  await context.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:4194' ? route.continue() : route.abort())
})
async function catalog(page, rows) {
  expect(rows.every(validPublicItem)).toBe(true)
  await page.route('**/rest/v1/rpc/read_shop_catalog', route => route.fulfill({ json: rows }))
}
test('unknown-only filters explain availability and preserve print/reset/history at seven widths', async ({ page }) => {
  test.setTimeout(120000)
  await catalog(page, [unknown()])
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  for (const width of [320, 360, 390, 430, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: width < 768 ? 844 : 1024 })
    await page.goto('/?age=8-12&venue=missing&group=2-6&print=invalid')
    await expect(page.getByRole('article')).toHaveCount(1)
    await expect(page.locator('#catalog-filter-age')).toBeDisabled()
    await expect(page.locator('#catalog-filter-age')).toHaveAccessibleDescription(/Возраст.*не указан/)
    await expect(page.locator('#catalog-filter-venue')).toBeDisabled()
    await expect(page.locator('#catalog-filter-venue')).toHaveAccessibleDescription(/Площадка.*не указана/)
    await expect(page.getByRole('note')).toContainText('Неизвестные параметры ссылки')
    await page.screenshot({ path: `qa/filter-availability/screens/unknown-catalog-${width}.png`, fullPage: true })
    const trigger = page.locator('#catalog-filter-trigger'), dialog = page.getByRole('dialog')
    await trigger.click()
    await expect(dialog.getByRole('checkbox')).toHaveCount(0)
    await expect(dialog.getByRole('radio')).toHaveCount(3)
    await expect(dialog.getByText('Возраст участников пока не указан.')).toBeVisible()
    await expect(dialog.getByText('Площадка пока не указана.')).toBeVisible()
    await expect(dialog.getByText('Размер группы пока не указан.')).toBeVisible()
    await expect(dialog.getByRole('button', { name: 'Закрыть фильтры' })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('button', { name: 'Сбросить фильтры' })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: 'Закрыть фильтры' })).toBeFocused()
    await dialog.getByLabel('Без печати', { exact: true }).check()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await trigger.click()
    await expect(dialog.getByLabel('Любая', { exact: true })).toBeChecked()
    await page.screenshot({ path: `qa/filter-availability/screens/unknown-dialog-${width}.png`, fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const [value, label] of [['none', 'Без печати'], ['required', 'С печатью']]) {
      await dialog.getByLabel(label, { exact: true }).check()
      await dialog.getByRole('button', { name: 'Показать 0 квестов' }).click()
      await expect(trigger).toBeFocused()
      await expect(page.getByRole('article')).toHaveCount(0)
      expect(new URL(page.url()).searchParams.get('print')).toBe(value)
      expect(new URL(page.url()).searchParams.has('age')).toBe(false)
      await page.reload()
      await expect(page.getByRole('heading', { name: 'По этим условиям квестов нет' })).toBeVisible()
      await page.getByRole('button', { name: `Снять условие: ${label}` }).click()
      await expect(page.getByRole('article')).toHaveCount(1)
      await page.goBack()
      await expect(page.getByRole('article')).toHaveCount(0)
      await page.goForward()
      await expect(page.getByRole('article')).toHaveCount(1)
      await trigger.click()
      await expect(dialog.getByLabel('Любая', { exact: true })).toBeChecked()
    }
    await dialog.getByLabel('Без печати', { exact: true }).check()
    await dialog.getByRole('button', { name: 'Сбросить фильтры' }).click()
    await expect(dialog.getByLabel('Любая', { exact: true })).toBeChecked()
    await dialog.getByRole('button', { name: 'Показать 1 квест', exact: true }).click()
    await expect(trigger).toBeFocused()
  }
  expect(errors).toEqual([])
})
test('single confirmed publication exposes its real age, venue and group', async ({ page }) => {
  await catalog(page, [publicRow(1)])
  await page.goto('/')
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.locator('#catalog-filter-age')).toBeEnabled()
  await expect(page.locator('#catalog-filter-venue')).toBeEnabled()
  await page.locator('#catalog-filter-trigger').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('8–12 лет')).toBeVisible()
  await expect(dialog.getByLabel('2–6 игроков')).toBeVisible()
  await expect(dialog.getByLabel('Помещение А', { exact: true })).toBeVisible()
  await dialog.getByLabel('2–6 игроков').check()
  await dialog.getByRole('button', { name: 'Показать 1 квест', exact: true }).click()
  await expect(page).toHaveURL(/group=2-6/)
})
test('mixed publications filter only confirmed claims and recover when metadata disappears', async ({ page }) => {
  let rows = [publicRow(1), unknown()]
  await page.route('**/rest/v1/rpc/read_shop_catalog', route => route.fulfill({ json: rows }))
  await page.goto('/')
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.locator('#catalog-filter-age').click()
  await page.getByRole('dialog').getByLabel('8–12 лет').check()
  await page.getByRole('dialog').getByRole('button', { name: 'Показать 1 квест', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  rows = [unknown()]
  await page.reload()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.locator('#catalog-filter-age')).toBeDisabled()
  await expect(page.getByRole('button', { name: /Снять условие:/ })).toHaveCount(0)
  await expect(page.getByRole('note')).toContainText('Неизвестные параметры ссылки')
})

import { expect, test } from '@playwright/test'

test.beforeEach(async ({ context }) => {
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
})

test('validates URL, full group coverage, OR and AND, reset focus', async ({ page }) => {
  await page.goto('/?group=4-8&group=4-8&group=bad&venue=park&unknown=ignored')
  await expect(page.getByRole('heading', { name: 'По этим условиям квестов нет' })).toBeVisible()
  await expect(page.getByRole('note')).toContainText('неизвестные значения не применены')
  await expect(page.getByRole('article')).toHaveCount(0)
  await page.getByRole('button', { name: 'Снять условие: В парке' }).click()
  await expect(page.getByRole('searchbox')).toBeFocused()
  await expect(page).toHaveURL(/\?group=4-8$/)
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.locator('.desktop-filter summary').click()
  await page.locator('.desktop-filter').getByLabel('2–5 игроков').check()
  await page.locator('.desktop-filter').getByRole('button', { name: 'Показать 2 квестов' }).click()
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.reload()
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.getByRole('button', { name: 'Сбросить все условия' }).click()
  await expect(page.getByRole('searchbox')).toBeFocused()
  await expect(page.getByRole('article')).toHaveCount(3)
})

test('query back and forward restore conditions, scroll and initiating focus', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.getByRole('searchbox').fill('тайна')
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toContainText('Тайна старого чердака')
  await expect(page).toHaveURL(`http://127.0.0.1:4186/?${new URLSearchParams({ q: 'тайна' })}`)
  await page.getByRole('searchbox').fill('звезды')
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toContainText('Секрет забытой обсерватории')
  await expect(page).toHaveURL(`http://127.0.0.1:4186/?${new URLSearchParams({ q: 'звезды' })}`)
  await page.goBack()
  await expect(page.getByRole('searchbox')).toHaveValue('тайна')
  await expect(page.getByRole('button', { name: 'Найти', exact: true })).toBeFocused()
  await page.goForward()
  await expect(page.getByRole('searchbox')).toHaveValue('звезды')
  await expect(page.getByRole('button', { name: 'Найти', exact: true })).toBeFocused()
  const card = page.getByRole('link', { name: 'Подробнее: Секрет забытой обсерватории' })
  await card.focus(); await card.scrollIntoViewIfNeeded()
  const y = await page.evaluate(() => scrollY)
  await card.click()
  await expect(page.locator('h1')).toHaveText('Секрет забытой обсерватории')
  await page.goBack()
  await expect(card).toBeFocused()
  await expect.poll(() => page.evaluate(() => scrollY)).toBeCloseTo(y, -1)
  await page.goForward()
  await expect(page.locator('h1')).toHaveText('Секрет забытой обсерватории')
})

test('local source fails on connection loss then retries with the same URL filters', async ({ page, context }) => {
  await page.goto('/?__qa=network&group=4-8')
  await expect(page.getByRole('status')).toContainText('Загружаем')
  await expect(page.getByRole('searchbox')).toBeDisabled()
  await context.setOffline(true)
  await expect(page.getByRole('alert')).toContainText('Не удалось загрузить')
  await expect(page.getByRole('article')).toHaveCount(0)
  await page.getByRole('button', { name: 'Повторить загрузку' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Загружаем')
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Повторить загрузку' })).toBeFocused()
  await context.setOffline(false)
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('Загружаем')
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('searchbox')).toBeFocused()
  await expect(page.getByRole('article')).toContainText('Тайна старого чердака')
  await expect(page).toHaveURL(/group=4-8/)
})

test('mobile draft groups and unbroken long names reflow at all required widths', async ({ page }) => {
  for (const width of [320, 360, 390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/?__qa=long')
    await expect(page.getByRole('article')).toHaveCount(3)
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.locator('.mobile-filter').click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('4–8 игроков').check()
    await expect(dialog.getByRole('button', { name: 'Показать 1 квестов' })).toBeVisible()
    await expect(page.getByRole('article')).toHaveCount(3)
    await dialog.getByRole('button', { name: 'Закрыть фильтры' }).click()
    await expect(page.locator('.mobile-filter')).toBeFocused()
    await page.locator('.mobile-filter').click()
    await expect(dialog.getByLabel('4–8 игроков')).not.toBeChecked()
    await dialog.getByLabel('4–8 игроков').check()
    await dialog.getByRole('button', { name: 'Показать 1 квестов' }).click()
    await expect(page.getByRole('article')).toHaveCount(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Сбросить все условия' }).click()
    await expect(page.getByRole('article')).toHaveCount(3)
  }
})

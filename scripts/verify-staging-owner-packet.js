import {readFileSync, writeFileSync} from 'node:fs'
import {expect} from 'vitest'

// Only called after the existing harness verifies ownership of its fresh local DB.
export function verifyStagingOwnerPacket({sql, historical}) {
  const file = name => readFileSync(new URL(`../docs/qa/staging-owner-packet-20261007/${name}`, import.meta.url),'utf8')
  const preflight=file('01-preflight.sql'), post=file('03-postcheck.sql'), unconfirmed=file('02-apply.sql')
  const apply=unconfirmed.replace('__OWNER_CONFIRM_PROJECT_AFTER_PREFLIGHT__','jeugfyaqzfgdvfhdxfht')
  sql(`create schema supabase_migrations;
    create table supabase_migrations.schema_migrations(version text primary key,name text,statements text[]);
    insert into supabase_migrations.schema_migrations(version) values ${historical.map(name=>`('${name.split('_')[0]}')`).join(',')};`)
  for(const release of JSON.parse(file('source-manifest.json')).knownReleases) {
    const source=readFileSync(new URL(`../${release.file}`,import.meta.url)).toString('base64')
    const name=release.file.split('/').at(-1).slice(15,-4)
    // Seed history only in a fresh fixture; never execute/adopt the known releases.
    sql(`insert into supabase_migrations.schema_migrations values('${release.id}','${name}',array[convert_from(decode('${source}','base64'),'UTF8')])`)
  }
  const releaseRows=()=>sql("select row_to_json(m) from supabase_migrations.schema_migrations m where version in ('20261003000000','20261003010000') order by version")
  const priorRelease=releaseRows()
  const unchangedRelease=()=>expect(releaseRows()).toBe(priorRelease)
  expect(sql(preflight)).toContain('326')
  const rpcMetadata=JSON.parse(sql(`select jsonb_agg(jsonb_build_object('name',p.proname,'signature',pg_get_function_identity_arguments(p.oid),'security_definer',p.prosecdef,'config',p.proconfig,'acl',p.proacl,'sha256',encode(sha256(convert_to(pg_get_functiondef(p.oid),'UTF8')),'hex')) order by p.proname) from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname in ('get_participant_profile_card','search_participant_group_members')`))
  writeFileSync(new URL('../.review.local/staging-preflight-rpc-evidence.json',import.meta.url),JSON.stringify(rpcMetadata,null,2))
  const compact=file('01-summary.sql')
  const summary=JSON.parse(sql(compact))
  expect(summary.preflight_passed).toBe(true)
  expect(summary.history_count).toBe(326)
  expect(summary.failed_guards).toEqual([])
  writeFileSync(new URL('../.review.local/staging-preflight-summary-evidence.json',import.meta.url),JSON.stringify(summary,null,2))
  const wrongRpc=JSON.parse(sql(compact.replace('begin read only;',"begin; alter function public.get_participant_profile_card(uuid) set jit='on';")))
  expect(wrongRpc.rpc_hashes_and_acl_match).toBe(false)
  expect(wrongRpc.preflight_passed).toBe(false)
  const selectedOnly=JSON.parse(sql(compact.replace('begin read only;','begin;')))
  expect(selectedOnly.preflight_passed).toBe(false)
  expect(selectedOnly.all_original_guards_passed).toBe(true)
  const driftSummary=JSON.parse(sql(compact.replace('begin read only;',"begin; delete from supabase_migrations.schema_migrations where version='20261003000000';")))
  expect(driftSummary.all_original_guards_passed).toBe(false)
  expect(driftSummary.failed_guards.join(' ')).toContain('326 version set')
  const diagnostic=JSON.parse(sql(file('00-history-diagnostic.sql')))
  expect(diagnostic.missing_vs_current).toEqual([])
  expect(diagnostic.extra_vs_current).toEqual([])
  expect(diagnostic.known_release_ids_present).toEqual(['20261003000000','20261003010000'])
  expect(diagnostic.pending_feature_ids_present).toEqual([])
  const originalVersion=historical[0].split('_')[0]
  const missing=apply.replace('begin;','begin; delete from supabase_migrations.schema_migrations where version=\'20261003000000\';')
  expect(()=>sql(missing)).toThrow(/version set/)
  unchangedRelease()
  sql(`update supabase_migrations.schema_migrations set version='20990101000000' where version='${originalVersion}'`)
  expect(()=>sql(apply)).toThrow(/version set/)
  sql(`update supabase_migrations.schema_migrations set version='${originalVersion}' where version='20990101000000'`)
  sql('alter table supabase_migrations.schema_migrations drop constraint schema_migrations_pkey')
  sql(`insert into supabase_migrations.schema_migrations(version,name) values('${originalVersion}','synthetic duplicate')`)
  expect(()=>sql(apply)).toThrow(/version set/)
  sql("delete from supabase_migrations.schema_migrations where name='synthetic duplicate'; alter table supabase_migrations.schema_migrations add primary key(version)")
  expect(()=>sql(unconfirmed)).toThrow()
  expect(sql("select to_regclass('public.account_activity') is null")).toBe('t')
  sql("insert into supabase_migrations.schema_migrations(version) values('unexpected-local-fixture')")
  expect(()=>sql(apply)).toThrow()
  sql("delete from supabase_migrations.schema_migrations where version='unexpected-local-fixture'")
  sql("create table public.account_activity(synthetic_id integer)")
  expect(()=>sql(apply)).toThrow()
  sql("drop table public.account_activity")
  unchangedRelease()
  // Force failure in migration 2: migration 1 and its history must roll back too.
  const injected=apply.replace("insert into supabase_migrations.schema_migrations(version,name,statements) values('20261006020000'", "raise exception 'synthetic post-migration failure';\ninsert into supabase_migrations.schema_migrations(version,name,statements) values('20261006020000'")
  expect(()=>sql(injected)).toThrow()
  expect(sql("select count(*) from storage.buckets where id='participant-avatars'")).toBe('0')
  expect(sql('select count(*) from supabase_migrations.schema_migrations')).toBe('326')
  unchangedRelease()
  sql(apply)
  const receipt=sql(post)
  for(const hash of JSON.parse(file('source-manifest.json')).migrations.map(m=>m.sha256)) expect(receipt).toContain(hash)
  expect(sql('select count(*) from supabase_migrations.schema_migrations')).toBe('328')
  unchangedRelease()
  expect(()=>sql(apply)).toThrow()
  expect(sql('select count(*) from supabase_migrations.schema_migrations')).toBe('328')
  unchangedRelease()
  sql(`update supabase_migrations.schema_migrations set version='20990101000000' where version='${originalVersion}'`)
  expect(()=>sql(post)).toThrow(/version set/)
  sql(`update supabase_migrations.schema_migrations set version='${originalVersion}' where version='20990101000000'`)
  for(const id of ['20261006010000','20261006020000']) {
    const tamper=post.replace('begin read only;',`begin; update supabase_migrations.schema_migrations set statements=array['tampered'] where version='${id}';`)
    expect(()=>sql(tamper)).toThrow(/source history mismatch/)
  }
  sql(post)
  unchangedRelease()
}
